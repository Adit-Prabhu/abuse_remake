"""Compare the vendored data with two original Crack dot Com releases.

Downloads, into the git-ignored ``cache/original-releases/`` folder:

- the 1995 DOS shareware release v1.01 (archive.org item ``Abuse_454``, ``ABUSE101.zip``);
- the 1996 retail data library 2.00 (``abuse-lib-2.00.tar.gz`` from abuse.zoy.org).

Each download is checked against a pinned SHA-256. The archives are only read as data and
nothing in them is executed. The script prints a Markdown report; ``docs/data-lineage.md``
holds its output.

    uv run python scripts/compare_original_data.py > docs/data-lineage.md

The retail 2.00 data is not public domain, so it is downloaded for comparison only and is never
committed.
"""

from __future__ import annotations

import hashlib
import io
import sys
import tarfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from abuse_remake.formats.lisp_reader import head, read_forms  # noqa: E402
from abuse_remake.formats.spec import SpecFile  # noqa: E402
from abuse_remake.formats.tiles import Palette  # noqa: E402

RELEASES = {
    "shareware-1.01": (
        "https://archive.org/download/Abuse_454/ABUSE101.zip",
        "4e3db6ca92e53d9cd5037127fb0d4d061f017ded8426fdb2a1e80f888ba5a4df",
    ),
    "retail-2.00": (
        "http://abuse.zoy.org/raw-attachment/wiki/download/abuse-lib-2.00.tar.gz",
        "263997a5e4ea70ac3d187de824c09b9a6b4ce778bbec5d8cf8372c54b34b81df",
    ),
}
VENDORED = ROOT / "data" / "original"
CACHE = ROOT / "cache" / "original-releases"
DEF_HEADS = {"defun", "def_char", "make_ammo_icon", "make_top_char", "def_explo",
             "make_hidden_wall_char", "make_smart_plat", "setq", "def_sound"}


def fetch(name: str) -> dict[str, bytes]:
    """Return {lower-case relative path: bytes} for one release."""
    url, digest = RELEASES[name]
    CACHE.mkdir(parents=True, exist_ok=True)
    archive = CACHE / url.rsplit("/", 1)[1]
    if not archive.exists():
        with urllib.request.urlopen(url, timeout=120) as resp:  # noqa: S310 - pinned URL
            archive.write_bytes(resp.read())
    data = archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit(f"{archive}: SHA-256 mismatch; refusing to compare")
    files: dict[str, bytes] = {}
    if archive.suffix == ".zip":
        with zipfile.ZipFile(io.BytesIO(data)) as z:
            for info in z.infolist():
                if not info.is_dir():
                    files[info.filename.lower()] = z.read(info)
    else:
        with tarfile.open(fileobj=io.BytesIO(data)) as t:
            for m in t.getmembers():
                if m.isfile():
                    rel = m.name.split("/unpacked/", 1)[-1].lower()
                    files[rel] = t.extractfile(m).read()
    return files


def vendored() -> dict[str, bytes]:
    return {str(p.relative_to(VENDORED)).lower(): p.read_bytes()
            for p in VENDORED.rglob("*") if p.is_file()}


def definitions(files: dict[str, bytes]) -> dict[tuple[str, str], tuple[str, str, int]]:
    out = {}
    for rel, raw in sorted(files.items()):
        if not (rel.startswith("lisp/") and rel.endswith(".lsp")):
            continue
        text = raw.decode("latin-1").replace("\r", "")
        try:
            forms = read_forms(text, rel)
        except ValueError:
            continue  # the translated-string files are not needed and do not parse
        for loc in forms:
            h = head(loc.form)
            if h in DEF_HEADS and len(loc.form) > 1:
                name = loc.form[1]
                if isinstance(name, list) and len(name) == 2:  # 'SYMBOL in a macro call
                    name = name[1]
                out[(h, str(name))] = (repr(loc.form), rel, loc.line)
    return out


def palette(files: dict[str, bytes]) -> tuple:
    return Palette.from_spec(SpecFile(files["art/back/backgrnd.spe"]), "palette").colors


def main() -> int:
    ours = vendored()
    our_defs = definitions(ours)
    print("# Data lineage report\n")
    print("Generated by `scripts/compare_original_data.py`. It compares `data/original/` with two")
    print("original Crack dot Com releases, each checked against a pinned SHA-256.")
    print("Lisp is compared form by form, ignoring comments and whitespace.\n")
    for name in RELEASES:
        files = fetch(name)
        print(f"## Versus {name}\n")
        print(f"Source: `{RELEASES[name][0]}` (SHA-256 `{RELEASES[name][1][:16]}…`)\n")
        lv = files.get("levels/level01.spe")
        print(f"- `levels/level01.spe` byte-identical: **{lv == ours['levels/level01.spe']}**")
        for rel in ("levels/level00.spe", "levels/level02.spe"):  # Remastered's campaign levels
            got = files.get(rel)
            print(f"- `{rel}` byte-identical: **{got == ours[rel]}**" if got is not None
                  else f"- `{rel}`: not in this release")
        print(f"- palette in `art/back/backgrnd.spe` identical: **{palette(files) == palette(ours)}**")
        art_same, art_diff, art_missing = [], [], []
        for rel in sorted(k for k in files if k.startswith("art/") and k.endswith(".spe")):
            if rel not in ours:
                art_missing.append(rel)
            elif files[rel] == ours[rel]:
                art_same.append(rel)
            else:
                art_diff.append(rel)
        print(f"- art files byte-identical: {len(art_same)}; differing: {len(art_diff)} "
              f"({', '.join(art_diff) or 'none'}); not vendored: {len(art_missing)}")
        theirs = definitions(files)
        same = [k for k in our_defs if k in theirs and theirs[k][0] == our_defs[k][0]]
        differ = [k for k in our_defs if k in theirs and theirs[k][0] != our_defs[k][0]]
        only_ours = [k for k in our_defs if k not in theirs]
        print(f"- Lisp definitions identical: {len(same)}; differing: {len(differ)}; "
              f"only in vendored copy: {len(only_ours)}\n")
        if differ:
            print("| Differing definition | Vendored location |")
            print("|---|---|")
            for k in differ:
                _, rel, line = our_defs[k]
                print(f"| `{k[0]} {k[1]}` | `data/original/{rel}:{line}` |")
            print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
